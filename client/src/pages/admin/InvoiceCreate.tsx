import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { api, type Paged } from '@/lib/api';
import { todayIso } from '@/lib/format';
import { useAction } from '@/lib/hooks';
import { Button } from '@/components/ui/button';
import { Card, CardBody, CardHeader, Field, Input, Select, Textarea } from '@/components/ui/primitives';
import { PageHeader } from '@/components/ui/feedback';
import { BackLink } from '@/components/layout/AppShell';
import { LinesEditor, type LinesValue } from '@/components/LinesEditor';
import { CustomerPicker } from '@/components/CustomerPicker';

export default function InvoiceCreate() {
  const navigate = useNavigate();
  const [customerId, setCustomerId] = useState('');
  const [subscriptionId, setSubscriptionId] = useState('');
  const [invoiceDate, setInvoiceDate] = useState(todayIso());
  const [terms, setTerms] = useState(15);
  const [notes, setNotes] = useState('');
  const [lines, setLines] = useState<LinesValue>({ lines: [{ type: 'PRODUCT', productId: '', variantId: null, quantity: 1, discountPercent: '0' }], discountId: null });
  const subs = useQuery({
    queryKey: ['customer-subs', customerId],
    queryFn: () => api.get<Paged<{ id: string; number: string; status: string }>>('/subscriptions', { customerId, pageSize: 100 }),
    enabled: Boolean(customerId),
  });
  const create = useAction(
    () =>
      api.post<{ data: { id: string } }>('/invoices', {
        customerId,
        subscriptionId: subscriptionId || null,
        invoiceDate,
        paymentTermsDays: terms,
        notes: notes || null,
        discountId: lines.discountId,
        lines: lines.lines.filter((l) => l.productId),
      }),
    { success: 'Draft invoice created', invalidate: [['invoices']], onSuccess: (r) => navigate(`/invoices/${r.data.id}`) },
  );
  const valid = customerId && lines.lines.some((l) => l.productId);

  return (
    <>
      <PageHeader back={<BackLink to="/invoices">Invoices</BackLink>} title="Manual invoice" description="For one-off charges such as onboarding or extra services. Recurring invoices are generated by billing runs." />
      <div className="space-y-6">
        <Card>
          <CardHeader title="Details" />
          <CardBody className="grid gap-4 md:grid-cols-4">
            <Field label="Customer" required className="md:col-span-2">
              {(p) => <CustomerPicker {...p} value={customerId} onChange={(id) => { setCustomerId(id); setSubscriptionId(''); }} />}
            </Field>
            <Field label="Related subscription">
              {(p) => (
                <Select {...p} value={subscriptionId} onChange={(e) => setSubscriptionId(e.target.value)} disabled={!customerId}>
                  <option value="">None</option>
                  {subs.data?.data.map((s) => <option key={s.id} value={s.id}>{s.number}</option>)}
                </Select>
              )}
            </Field>
            <div className="grid grid-cols-2 gap-2">
              <Field label="Invoice date">{(p) => <Input {...p} type="date" value={invoiceDate} onChange={(e) => setInvoiceDate(e.target.value)} />}</Field>
              <Field label="Terms (days)">{(p) => <Input {...p} type="number" min={0} value={terms} onChange={(e) => setTerms(Number(e.target.value))} />}</Field>
            </div>
          </CardBody>
        </Card>
        <Card>
          <CardHeader title="Lines" />
          <CardBody>
            <LinesEditor value={lines} onChange={setLines} date={invoiceDate} allowPlanLines={false} subscriptionId={subscriptionId || undefined} />
          </CardBody>
        </Card>
        <Card>
          <CardBody>
            <Field label="Notes">{(p) => <Textarea {...p} rows={2} value={notes} onChange={(e) => setNotes(e.target.value)} />}</Field>
          </CardBody>
        </Card>
        <div className="flex justify-end gap-3">
          <Button variant="secondary" onClick={() => navigate(-1)}>Cancel</Button>
          <Button disabled={!valid} loading={create.isPending} onClick={() => create.mutate()}>Create draft invoice</Button>
        </div>
      </div>
    </>
  );
}
